#!/usr/bin/env python3
"""Generate the Heavy Unit .mra files from the ROM table in hvyunit_roms.py.

    gen_hvyunit_mra.py [--out mra] [--fast] [--check [--zip PATH]]

The ROM table (names, CRCs, offsets) lives only in hvyunit_roms.py; this writes
one MRA per set whose parts reproduce exactly the image that tool builds, and
--check proves it by replaying the MRA loader's semantics on the real zip
(parts concatenated in order, `repeat` fills) and comparing md5s.

--fast adds address="0x32000000" to the ROM image (Main_MiSTer then copies the
whole image to the DDR3 in one go; see docs/fast-load.md).  Off by default.

Image layout (hvyunit_roms.py):  main 128K | sub 64K | sound 64K | tiles 512K |
sprites 2M | Mermaid 4K  =  0x2C1000 bytes.
"""
import argparse
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import hvyunit_roms as R   # noqa: E402

# region order in the image (hvyunit_roms.REGIONS) and the parts' region keys
ORDER = ["main", "sub", "sound", "tiles", "sprites", "mermaid"]

SETS_META = {
    "hvyunit":   dict(name="Heavy Unit (World)",                         parent=None,       region="World", japan=False),
    "hvyunitj":  dict(name="Heavy Unit (Japan, newer)",                  parent="hvyunit",  region="Japan", japan=True),
    "hvyunitja": dict(name="Heavy Unit (Japan, alternate ROM format)",   parent="hvyunit",  region="Japan", japan=True),
    "hvyunitjo": dict(name="Heavy Unit (Japan, older)",                  parent="hvyunit",  region="Japan", japan=True),
    "hvyunitu":  dict(name="Heavy Unit -U.S.A. Version- (US)",           parent="hvyunit",  region="USA",   japan=True),
}

# MAME's input ports for DSW1 / DSW2 (hvyunit.cpp); "japan" is the hvyunitj layout,
# which has no Coin Mode switch and different coin steps.
def switches(japan):
    dsw1 = ['<dip name="Cabinet" bits="0" ids="Upright,Cocktail"/>',
            '<dip name="Flip Screen" bits="1" ids="On,Off"/>',
            '<dip name="Service Mode" bits="2" ids="On,Off"/>']
    if japan:
        dsw1 += ['<dip name="Coin A" bits="4,5" ids="2C/3C,2C/1C,1C/2C,1C/1C"/>',
                 '<dip name="Coin B" bits="6,7" ids="2C/3C,2C/1C,1C/2C,1C/1C"/>']
    else:
        dsw1 += ['<dip name="Coin Mode" bits="3" ids="Mode 2,Mode 1"/>',
                 '<dip name="Coin A" bits="4,5" ids="1C/6C (Mode 2: 1C/4C),1C/2C (Mode 2: 1C/3C),2C/1C,1C/1C"/>',
                 '<dip name="Coin B" bits="6,7" ids="1C/6C (Mode 2: 1C/4C),1C/2C (Mode 2: 1C/3C),2C/1C,1C/1C"/>']
    dsw2 = ['<dip name="Difficulty" bits="8,9" ids="Hardest,Hard,Easy,Normal"/>',
            '<dip name="Allow Continue" bits="10" ids="Off,On"/>',
            '<dip name="Bonus" bits="11" ids="On,Off"/>',
            '<dip name="Lives" bits="12,13" ids="7,5,4,3"/>',
            '<dip name="Demo Sounds" bits="14" ids="Off,On"/>']
    return dsw1 + dsw2


def parts_for(setname):
    """-> list of ('part', name, crc, size) / ('fill', size) in image order."""
    spec = R.SETS[setname]["roms"]
    out = []
    for region in ORDER:
        base, size = R.REGION[region]
        items = sorted((off, nm, sz, crc) for (rg, nm, off, sz, crc) in spec if rg == region)
        pos = 0
        for off, nm, sz, crc in items:
            if off > pos:
                out.append(("fill", off - pos))
            out.append(("part", nm, crc, sz))
            pos = off + sz
        if pos < size:
            out.append(("fill", size - pos))
    return out


def mra_text(setname, fast):
    m = SETS_META[setname]
    zips = "%s.zip" % setname + ("|%s.zip" % m["parent"] if m["parent"] else "")
    attrs = 'index="0" zip="%s" md5="None"' % zips
    if fast:
        attrs += ' address="0x32000000"'
    L = []
    a = L.append
    a("<misterromdescription>")
    a("    <rotation>horizontal</rotation>")
    a("    <name>%s</name>" % m["name"])
    a("    <setname>%s</setname>" % setname)
    a("    <mameversion>0289</mameversion>")
    a("    <year>1988</year>")
    a("    <manufacturer>Kaneko / Taito</manufacturer>")
    a("    <players>2</players>")
    a("    <joystick>8</joystick>")
    a("    <rbf>heavyunit</rbf>")
    a("    <region>%s</region>" % m["region"])
    a("")
    a("    <!--")
    a("      Flat image for the Heavy Unit core (target/mister/hvyunit_mem.sv), 0x2C1000 bytes:")
    a("")
    a("        0x000000  0x020000  main Z80 program (8 banks of 16 KB)")
    a("        0x020000  0x010000  sub  Z80 program (4 banks)")
    a("        0x030000  0x010000  sound Z80 program (4 banks)")
    a("        0x040000  0x080000  background tiles, 16x16 4bpp")
    a("        0x0C0000  0x200000  Pandora sprites, 16x16 4bpp (gaps are zero, as MAME's ROMREGION_ERASE00)")
    a("        0x2C0000  0x001000  Mermaid 8751 firmware (0x0E00 bytes, zero padded)")
    a("")
    a("      Generated by tools/gen_hvyunit_mra.py from tools/hvyunit_roms.py. Expects the MAME 0.289")
    a("      merged romset (hvyunit.zip) or the split sets; parts are found by name or CRC, whatever")
    a("      folder holds them.")
    a("    -->")
    a("    <rom %s>" % attrs)
    cur = None
    for p in parts_for(setname):
        if p[0] == "fill":
            a('        <part repeat="0x%X">00</part>' % p[1])
        else:
            a('        <part name="%s" crc="%08x"/>' % (p[1], p[2]))
    a("    </rom>")
    a("")
    a('    <switches default="FE,F7" base="16">')
    for d in switches(m["japan"]):
        a("        " + d)
    a("    </switches>")
    a("")
    a('    <buttons names="Fire,Bomb,Start 1P,Start 2P,Coin" default="A,B,Start,Select,R"/>')
    a("</misterromdescription>")
    return "\n".join(L) + "\n"


def replay(setname, by_crc):
    """The loader's view: concatenate parts / fills in order."""
    img = bytearray()
    for p in parts_for(setname):
        if p[0] == "fill":
            img += bytes(p[1])
        else:
            data = by_crc[p[2]]
            assert len(data) == p[3], (p[1], len(data), p[3])
            img += data
    return bytes(img)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="mra")
    ap.add_argument("--fast", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--zip", default=os.environ.get("HVYUNIT_ZIP", R.DEFAULT_ZIP))
    a = ap.parse_args()

    if a.check:
        by_crc = R.load_by_crc(a.zip)
        bad = 0
        for s in sorted(R.SETS):
            want = R.build_image(R.build_regions(s, by_crc))
            got = replay(s, by_crc)
            ok = (want == got) and len(got) == R.IMAGE_SIZE
            print("%-10s MRA replay %s  (%d bytes, md5 %s)" % (
                s, "== image tool" if ok else "DIFFERS", len(got), hashlib.md5(got).hexdigest()))
            bad += 0 if ok else 1
        return 1 if bad else 0

    os.makedirs(a.out, exist_ok=True)
    for s in sorted(R.SETS):
        path = os.path.join(a.out, SETS_META[s]["name"] + ".mra")
        with open(path, "w", newline="\n") as f:
            f.write(mra_text(s, a.fast))
        print("wrote", path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
